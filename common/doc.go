// Package common 提供密码学相关的通用基础工具函数，供 crypto 根包及各子包复用。
//
// 本包为零依赖子包（仅依赖标准库），不包含类型定义与业务逻辑，
// 仅提供三类基础工具：
//
//   - FillRandom：使用 crypto/rand 安全随机数完整填充字节切片；
//   - ZeroBytes：将字节切片逐字节清零（敏感数据内存擦除）；
//   - ZeroBigInt：清零大整数（敏感数据内存擦除）。
//
// 随机性来源为 crypto/rand（操作系统熵源），适合密钥、IV、nonce 等
// 安全敏感场景的生成；清零操作用于在敏感数据生命周期结束后及时擦除
// 密钥等内存内容，降低其滞留内存的时间窗口。
//
// 注意：Go 运行时与垃圾回收器无法保证清零后的内存不被重新分配或残留
// 副本，本包清零函数只降低敏感数据在堆上滞留的时间窗口，不构成绝对
// 的安全保证。
